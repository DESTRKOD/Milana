class ChatPayload(BaseModel):
    scenarioId: str
    userRole: str
    text: str

class DebriefPayload(BaseModel):
    history: list

@app.post("/api/chat")
async def chat_endpoint(payload: ChatPayload):
    try:
        if not client:
            return {"reply": "Ошибка: Не настроен GEMINI_API_KEY"}

        scenario_info = SCENARIOS_DATA.get(payload.scenarioId, SCENARIOS_DATA["1"])
        
        all_roles = list(scenario_info["roles"].keys())
        ai_role = next((r for r in all_roles if r != payload.userRole), all_roles[0])
        ai_role_goal = scenario_info["roles"].get(ai_role, "")
        user_role_goal = scenario_info["roles"].get(payload.userRole, "")

        prompt = f"""
        Ты — оппонент в управленческом поединке.
        СИТУАЦИЯ: {scenario_info['context']}
        Твоя роль: {ai_role} (Цель: {ai_role_goal})
        Роль оппонента: {payload.userRole} (Цель: {user_role_goal})
        
        Правила:
        1. Отвечай строго от первого лица.
        2. Отвечай разговорным языком, строго 1 короткое предложение (до 15 слов).
        3. Задавай встречный вопрос или перехватывай инициативу.
        
        Реплика оппонента: "{payload.text}"
        """
        
        # Вызов асинхронной модели нового SDK
        response = await client.aio.models.generate_content(
            model='gemini-1.5-flash-8b',
            contents=prompt,
            config=types.GenerateContentConfig(
                max_output_tokens=60,
                temperature=0.7
            )
        )
        return {"reply": response.text.strip()}
    except Exception as e:
        return {"reply": f"Ошибка ИИ: {str(e)}"}

@app.post("/api/debrief")
async def debrief_endpoint(payload: DebriefPayload):
    try:
        if not client:
            return {"analysis": "Ошибка: Не настроен GEMINI_API_KEY"}

        history_text = "\n".join(payload.history)
        
        prompt = f"""
        Ты — Судья турнира по переговорам. Кратко проанализируй поединок:
        {history_text}
        
        Дай разбор строго по 3 пунктам (максимум 80 слов):
        1. Удержание позиции
        2. Главная ошибка
        3. Совет для победы
        """
        
        response = await client.aio.models.generate_content(
            model='gemini-1.5-flash-8b',
            contents=prompt,
            config=types.GenerateContentConfig(
                max_output_tokens=250,
                temperature=0.5
            )
        )
        return {"analysis": response.text.strip()}
    except Exception as e:
        return {"analysis": f"Ошибка анализа: {str(e)}"}
